export type TranslationKey = keyof typeof messages.ar;

export function translate(language: Language, key: TranslationKey): string {
  return messages[language][key];
}

export function errorMessage(code: string, language: Language): string {
  if (code === "unauthorized") return translate(language, "loginFailed");
  if (code === "model_not_configured") return translate(language, "modelMissing");
  if (code === "model_provider_models_unavailable") return translate(language, "noModels");
  if (code.startsWith("model_provider_")) return translate(language, "modelError");
  if (["agent_not_found", "thread_not_found", "run_not_found"].includes(code)) {
    return translate(language, "genericError");
  }
  return translate(language, "genericError");
}
