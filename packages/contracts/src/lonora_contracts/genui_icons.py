_FOLDED = {name.lower(): name for name in ICON_NAMES}


def canonical_icon(value: object) -> str | None:
    if not isinstance(value, str) or len(value) > 40:
        return None
    if value in ICON_NAMES:
        return value
    parts = [part for part in re.split(r"[-_\s]+", value.strip()) if part]
    if not parts:
        return None
    return _FOLDED.get("".join(parts).lower())
